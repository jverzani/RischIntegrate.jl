# ---------------------------------------------------------------------------
# SI2 phase 3a: products of radicals of any index (simple radical / Kummer extensions)
#
# The radicands are factored into pairwise coprime squarefree bases bₖ ∈ ℤ[x] (primitive, lc > 0);
# a radical u^e is c^e Π bₖ^(e mₖ). An element of K = ℚ(x)(bₖ^(1/nₖ)) is Σ g_e θ_e over monomials
# θ_e = Π bₖ^(eₖ), eₖ ∈ [0, 1) (linearly independent over ℚ(x)). The θ_e are eigenvectors of the
# Kummer automorphisms bₖ^(1/nₖ) ↦ ζ bₖ^(1/nₖ) (over ℚ(ζ)(x)), so as for two square roots (step BQ)
# ∫f is elementary iff every ∫ g_e θ_e is. For one component θ = Π bₖ^(rₖ): θ′/θ = M/A with
# A = Π_{rₖ≠0} bₖ, M = Σ rₖ bₖ′ A/bₖ, and
#   d(C θ/Vᵏ) = θ (C′VA - kCV′A + CVM)/(A V^{k+1}).
#  * V | A, V | bₖ: M ≡ rₖ V′W mod V (A = VW), so the numerator over A Vᵏ is ≡ (rₖ - k) C V′W: every
#    power of V in D (integrand B/(A D)) is removed (rₖ ∉ ℤ). No residues there (the place is fixed
#    by the automorphisms, which multiply the differential by a root of unity ≠ 1).
#  * V coprime to A: V^m → V^{m-1} for m ≥ 2, as in Hermite reduction.
#  * at infinity: d(xᵏθ) = θ (k x^{k-1} A + xᵏ M)/A, leading coefficient lc(A)(k + ρ), ρ = Σ rₖ deg bₖ > 0:
#    deg P ≤ deg A - 2 for the remainder (P + R/D)/A·θ (D squarefree, coprime to A).
# Without residues (R = 0, and at ∞ none: always when ρ ∉ ℤ), the remainder is 0 or not elementary:
# ω = dv, v = Cθ with C a polynomial (a pole of C gives one of v, so a double pole of dv), and
# deg(C′A + CM) = deg C + deg A - 1 > deg P. Residues need the log part (phase 3b). Answers are
# valid where every base is positive (principal powers).
# ---------------------------------------------------------------------------

# Σ g_e θ_e: exponent vectors (fractional parts, one per base) => coefficient
struct KumEl
    t::Dict{Vector{Q},QXF}
end
kum_zero() = KumEl(Dict{Vector{Q},QXF}())
kum_const(nb::Int, g::QXF) = iszero(g) ? kum_zero() : KumEl(Dict(zeros(Q, nb) => g))
function kum_add(u::KumEl, v::KumEl)
    t = copy(u.t)
    for (e, g) in v.t
        h = get(t, e, zero(QXF)) + g
        iszero(h) ? delete!(t, e) : (t[e] = h)
    end
    KumEl(t)
end
kum_neg(u::KumEl) = KumEl(Dict(e => -g for (e, g) in u.t))
# θ_e θ_f = Π bₖ^⌊eₖ+fₖ⌋ θ_{frac(e+f)}
function kum_mul(bs::Vector{QX}, u::KumEl, v::KumEl)
    out = kum_zero()
    for (e, g) in u.t, (f, h) in v.t
        s = e .+ f
        fl = floor.(Int, s)
        c = g * h * prod((frac(bs[k])^fl[k] for k in eachindex(bs) if fl[k] != 0); init = one(QXF))
        out = kum_add(out, KumEl(Dict(s .- fl => c)))
    end
    out
end
# the inverse, by linear algebra on the subgroup generated by the support (u·v = 1)
function kum_inv(bs::Vector{QX}, u::KumEl)
    isempty(u.t) && throw(DivideError())
    nb = length(bs)
    if length(u.t) == 1
        (e, g), = u.t
        fl = [iszero(x) ? 0 : 1 for x in e]             # θ_e⁻¹ = θ_{1-e} Π bₖ^(-1) for eₖ ≠ 0
        c = inv(g) * prod((inv(frac(bs[k])) for k in 1:nb if fl[k] == 1); init = one(QXF))
        return KumEl(Dict([iszero(x) ? x : 1 - x for x in e] => c))
    end
    H = Set([zeros(Q, nb)])                             # the subgroup generated by the exponents
    while true
        n0 = length(H)
        for h in collect(H), e in keys(u.t)
            push!(H, mod.(h .+ e, 1))
        end
        length(H) == n0 && break
        length(H) > 36 && throw(RischNotImplemented("inverse of a sum of radicals: the group is too large"))
    end
    Hs = sort!(collect(H))
    idx = Dict(h => i for (i, h) in enumerate(Hs))
    cols = Vector{QXF}[]
    for h in Hs                                         # column: u·θ_h in the basis θ_H
        p = kum_mul(bs, u, KumEl(Dict(h => one(QXF))))
        col = [zero(QXF) for _ in Hs]
        for (e, g) in p.t
            col[idx[e]] = g
        end
        push!(cols, col)
    end
    rhs = [zero(QXF) for _ in Hs]
    rhs[idx[zeros(Q, nb)]] = one(QXF)
    sol = solve_columns(cols, rhs)
    sol === nothing && throw(DivideError())
    KumEl(Dict(Hs[i] => sol[i] for i in eachindex(Hs) if !iszero(sol[i])))
end
function kum_pow(bs, u::KumEl, k::Integer)
    k < 0 && return kum_pow(bs, kum_inv(bs, u), -k)
    r, s = kum_const(length(bs), one(QXF)), u
    while k > 0
        isodd(k) && (r = kum_mul(bs, r, s))
        k >>= 1
        k > 0 && (s = kum_mul(bs, s, s))
    end
    r
end

# a coprime squarefree basis (primitive integer polynomials, lc > 0) for the polynomials ps, and each
# p as c·Π bₖ^mₖ
function kum_primitive(p::QX)
    l = reduce(lcm, denominator.(p.c))
    q = QX(Q[c * l for c in p.c])
    g = reduce(gcd, numerator.(q.c))
    q = scale(Q(1) / g, q)
    lc(q) < 0 ? -q : q
end
function kum_basis(ps::Vector{QX})
    bs = QX[]
    for p in ps, (f, _) in squarefree(p)
        push!(bs, kum_primitive(f))
    end
    changed = true
    while changed                                       # refine to pairwise coprime
        changed = false
        for i in eachindex(bs), j in eachindex(bs)
            i < j || continue
            g = gcd(bs[i], bs[j])
            degree(g) > 0 || continue
            new = filter(f -> degree(f) > 0, [g, quo(bs[i], g), quo(bs[j], g)])
            bs = QX[QX[bs[k] for k in eachindex(bs) if k != i && k != j]; QX[kum_primitive(f) for f in new]]
            changed = true
            break
        end
    end
    QX[b for b in unique(bs)]
end
# p = c·Π bₖ^mₖ: (c, m)
function kum_exponents(bs::Vector{QX}, p::QX)
    m = zeros(Int, length(bs))
    for (k, b) in enumerate(bs)
        while true
            q, r = divrem(p, b)
            iszero(r) || break
            p, m[k] = q, m[k] + 1
        end
    end
    degree(p) == 0 || throw(RischError("kum_exponents: not a product of the bases"))
    p.c[1], m
end

# the term t in K; rad(ue, e) = the KumEl of ue^e (or nothing)
function parse_kum(t, xk::String, bs::Vector{QX}, rad)
    nb = length(bs)
    if safe_iscall(t)
        args = arguments(t)
        if !isempty(args)
            rp = radical_parts(t)
            if rp !== nothing
                ue = radicand_element(rp[2], xk)
                r = ue === nothing ? nothing : rad(ue, rp[1])
                r === nothing && throw(RischNotImplemented("radical $t: not supported here"))
                return r
            end
            n = opname(operation(t))
            v = KumEl[parse_kum(u, xk, bs, rad) for u in args]
            n === :+ && return foldl(kum_add, v)
            n === :- && return length(v) == 1 ? kum_neg(v[1]) : kum_add(v[1], kum_neg(foldl(kum_add, v[2:end])))
            n === :* && return foldl((f, g) -> kum_mul(bs, f, g), v)
            n === :/ && length(v) == 2 && return kum_mul(bs, v[1], kum_inv(bs, v[2]))
            n === :inv && length(v) == 1 && return kum_inv(bs, v[1])
            if n === :^ && length(v) == 2
                ks = v[2].t
                k = (length(ks) == 1 && haskey(ks, zeros(Q, nb))) ? const_int(ks[zeros(Q, nb)]) :
                    isempty(ks) ? 0 : nothing
                (k === nothing || abs(k) > 10_000) && throw(RischNotImplemented("only small integer powers are supported"))
                return kum_pow(bs, v[1], k)
            end
            throw(RischNotImplemented("`$n` with radicals: only rational functions of x and radicals are supported"))
        end
    end
    string(t) == xk && return kum_const(nb, frac(xpoly(Q)))
    r = leaf_rational(t)
    r !== nothing && return kum_const(nb, kconst(r))
    throw(RischNotImplemented("symbol `$t` is not the integration variable"))
end

# ∫ g θ, θ = Π bₖ^rₖ: (C with ∫ g θ = C θ) or the exception to raise
function kum_component(bs::Vector{QX}, r::Vector{Q}, g::QXF, θterm)
    ks = [k for k in eachindex(bs) if !iszero(r[k])]
    A = prod((bs[k] for k in ks); init = one(QX))
    M = sum((scale(r[k], deriv(bs[k]) * quo(A, bs[k])) for k in ks); init = zero(QX))
    rho = sum((r[k] * degree(bs[k]) for k in ks); init = Q(0))
    B, D = g.num * A, g.den                             # g = B/(A D)
    C = zero(QXF)
    while true
        h = gcd(B, D)
        if degree(h) > 0
            B, D = quo(B, h), quo(D, h)
        end
        step = nothing
        for (V0, m) in squarefree(D)
            Va = gcd(V0, A)
            if degree(Va) > 0                           # V | A: all of V^m, k = m
                kk = findfirst(k -> degree(gcd(Va, bs[k])) > 0, ks)
                Vb = gcd(Va, bs[ks[kk]])                # inside one base
                step = (Vb, m, r[ks[kk]])
                break
            elseif m >= 2
                step = (quo(V0, Va), m, nothing)
                break
            end
        end
        step === nothing && break
        V, m, rk = step
        Ds = quo(D, V^m)
        dV = deriv(V)
        if rk !== nothing                               # numerator over A V^k: C′A - kCV′W + CM, k = m
            k, W = m, quo(A, V)
            Cc = hyp_solve_mod(B, scale(rk - k, Ds * dV * W), V)
            Nn = deriv(Cc) * A - scale(Q(k), Cc * dV * W) + Cc * M
            r0, z = divrem(B - Ds * Nn, V)
        else                                            # over A V^{k+1}: C′VA - kCV′A + CVM, k = m - 1
            k = m - 1
            Cc = hyp_solve_mod(B, scale(Q(-k), Ds * dV * A), V)
            Nn = deriv(Cc) * V * A - scale(Q(k), Cc * dV * A) + Cc * V * M
            r0, z = divrem(B - Ds * Nn, V)
        end
        iszero(z) || throw(RischError("kum_component: numerator not divisible"))
        C = C + frac(Cc, V^k)
        B, D = r0, Ds * V^(m - 1)
    end
    P, R = divrem(B, D)
    while degree(P) >= degree(A) - 1                   # at infinity: d(xᵏθ)
        k = degree(P) - degree(A) + 1
        c = lc(P) / (lc(A) * (k + rho))
        xk = xpoly(Q)^k
        P = P - scale(c, (k == 0 ? zero(QX) : scale(Q(k), xpoly(Q)^(k - 1) * A)) + xk * M)
        C = C + frac(scale(c, xk))
    end
    # exact check: C′ + C M/A + (P + R/D)/A = g
    dx(C) + C * frac(M, A) + frac(P, A) + frac(R, A * D) == g ||
        throw(RischError("internal check failed: Hermite reduction for a product of radicals"))
    (iszero(P) && iszero(R)) && return C
    iszero(R) || return RischNotImplemented(
        "∫ (…)·$θterm: residues at finite places; the logarithmic part for radicals of index ≥ 3 is not " *
        "implemented yet (SI2 phase 3b)")
    if isone(denominator(rho))                          # possible residue at ∞: the x⁻¹ coefficient of P Π bₖ^(rₖ-1)
        N = degree(P) + 2
        s = [Q(1); zeros(Q, N)]
        for k in ks
            sk = hyp_sqrt_series(bs[k], N, r[k] - 1)
            s = [sum(s[i + 1] * sk[j - i + 1] for i in 0:j) for j in 0:N]
        end
        e0 = Int(rho) - degree(A)                       # P/A θ ∝ x^e0 P(x) S(1/x)
        res = sum((P.c[j + 1] * s[j + e0 + 2] for j in 0:degree(P) if 0 <= j + e0 + 1 <= N); init = Q(0))
        iszero(res) || return RischNotImplemented(
            "∫ (…)·$θterm: residues at infinity; the logarithmic part for radicals of index ≥ 3 is not " *
            "implemented yet (SI2 phase 3b)")
    end
    NotElementary("after Hermite reduction ∫ ($(zpoly_string(P, "x")))/($(zpoly_string(A, "x")))·$θterm is left: " *
                  "a nonzero differential without residues")
end

function integrate_kummer(f, x, rads; build = nothing, lift = nothing, verify::Bool = true)
    xk = string(x)
    b0 = Builder(build === nothing ? auto_build(f, x) : build, lift === nothing ? auto_lift(f, x) : lift, x)
    us = Any[]
    for (e, ut) in rads
        ue = radicand_element(ut, xk)
        ue === nothing && throw(RischNotImplemented("radical of a non-rational expression ($ut)"))
        push!(us, ue)
    end
    bs = kum_basis(vcat(QX[u.num for u in us], QX[u.den for u in us]))
    isempty(bs) && throw(RischNotImplemented("only constant radicands"))
    nb = length(bs)
    rad = function (ue, e)
        cn, mn = kum_exponents(bs, ue.num)
        cd, md = kum_exponents(bs, ue.den)
        c, m = cn / cd, mn .- md
        ce = iszero(c) ? nothing : c > 0 ? rat_root(c^numerator(e), Int(denominator(e))) : nothing
        ce === nothing && throw(RischNotImplemented("the constant factor $c of a radicand: c^$e is not rational"))
        s = e .* m
        fl = floor.(Int, s)
        g = kconst(ce) * prod((frac(bs[k])^fl[k] for k in 1:nb if fl[k] != 0); init = one(QXF))
        KumEl(Dict(s .- fl => g))
    end
    el = parse_kum(f, xk, bs, rad)
    terms = Any[]
    rss = Any[]
    for (e, g) in sort!(collect(el.t); by = first)
        if all(iszero, e)
            T, _ = build_tower(b0.x, xk)
            F = integrate_built(T, g, b0, verify)
            if F isa IntegralWithRootSums
                append!(rss, F.rootsums)
                F = F.elementary
            end
            push!(terms, F)
            continue
        end
        θs = Any[mk(b0, :^, poly_term(b0, bs[k]), b0.lift(e[k])) for k in 1:nb if !iszero(e[k])]
        θterm = length(θs) == 1 ? θs[1] : mk(b0, :*, θs...)
        C = kum_component(bs, e, g, θterm)
        C isa Exception && throw(C)
        iszero(C) || push!(terms, mk(b0, :*, frac_term(b0, C), θterm))
    end
    E = isempty(terms) ? b0.lift(0) : length(terms) == 1 ? terms[1] : mk(b0, :+, terms...)
    isempty(rss) ? E : IntegralWithRootSums(E, rss, xk)
end
